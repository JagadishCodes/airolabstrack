				Confidentiality, Integrity, and Availability of Information
			</p>
			<p>
				<strong>a. Access Control:</strong>
Suppliers shall implement robust access controls, including role-based access, strong authentication, and authorization mechanisms, as specified by AiRo Digital Labs.<br><br>
<strong>b. Data Encryption:</strong>
Suppliers must encrypt sensitive data both at rest and in transit using industry-standard encryption protocols approved by AiRo Digital Labs.<br><br>
<strong>c. Regular Audits:</strong>
Suppliers shall conduct periodic security audits and assessments to identify vulnerabilities and ensure compliance with AiRo Digital Labs' security policies.<br><br>
<strong>d. Incident Response Plan:</strong>
Suppliers must develop and maintain an incident response plan to address security breaches promptly and effectively in accordance with AiRo Digital Labs' guidelines.<br><br>
<strong>e. Employee Training:</strong>
Suppliers shall provide comprehensive security training to their employees to raise awareness and educate them on security best practices as defined by AiRo Digital Labs. AiRo Digital Labs expects the Supplier to demonstrate this as and when required. 

			</p>
