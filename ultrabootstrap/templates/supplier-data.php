			<p class="content-subtitle">
				 Definitions
			</p>
			<p>
				For the purpose of this policy:<br><br>
<strong>a. Supplier:</strong> Any individual, company, or entity that provides goods, services, or access to systems or data to AiRo Digital Labs.<br><br>
<strong>b. MSA (Master Services Agreement) / MCA (Master Consulting Agreement):</strong> A formal written agreement that outlines the terms and conditions under which a Supplier provides goods or services to AiRo Digital Labs.<br><br>
<strong>c. NDA (Non-Disclosure Agreement):</strong> A legally binding agreement that governs the sharing of confidential information between AiRo Digital Labs and a Supplier.<strong><br><br>
d. Confidential Information:</strong> Any information, data, or material that is not publicly available or generally known, which is considered sensitive, proprietary, or confidential by AiRo Digital Labs. This includes, but is not limited to, trade secrets, customer data, business plans, financial information, pricings and costs,  proprietary software, and any information marked as "confidential."<br><br>
<strong>e. Data Encryption:</strong> The process of converting plain-text data into an unreadable format (cipher text) using encryption algorithms and encryption keys to protect data confidentiality.<br><br>
<strong>f. Incident Response Plan:</strong> A documented strategy outlining the actions to be taken when a security incident or data breach occurs, including procedures for identifying, containing, and mitigating the incident.<br><br>
<strong>g. Data Classification Framework:</strong> A systematic approach for categorizing data based on its sensitivity or criticality to the organization, often using labels such as "confidential," "internal use only," or "public."<br><br>
<strong>h. Encryption Protocols:</strong> Secure communication methods and standards, such as SSL/TLS, IPsec, or PGP, used to protect data during transmission over networks.<br><br>
<strong>i. Vulnerability Assessment:</strong> A systematic process of identifying and evaluating weaknesses in systems, applications, or processes that could be exploited by attackers.<br><br>
<strong>j. Penetration Testing:</strong> A simulated attack on a computer system or network to identify vulnerabilities and assess security controls.<br><br>
<strong>k. Data Retention Policy:</strong> A documented policy that defines how long data should be retained and when it should be securely disposed of or archived based on legal, business, and regulatory requirements.<br><br>
<strong>l. Access Control Systems:</strong> Technical and physical mechanisms, such as key cards, biometrics, and authentication protocols, used to regulate access to facilities or systems.

			</p>
