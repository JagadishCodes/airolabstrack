In the event of non-compliance, Suppliers are required to develop a corrective action plan that includes root cause analysis and preventive measures. These plans must be shared with AiRo Digital Labs.<br><br>
<strong>d. Documentation:</strong>
Suppliers shall maintain documentation of all non-compliance incidents and actions taken for future reference and improvement. These records must be made available to AiRo Digital Labs upon request.

