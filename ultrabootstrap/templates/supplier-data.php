			<p class="content-subtitle">
				Information Transfer and Security
			</p>
			<p>
				<strong>a. Data Classification:</strong>
Suppliers shall classify data based on its sensitivity to determine appropriate transfer mechanisms and security controls in alignment with AiRo Digital Labs' data classification framework.<br><br>
<strong>b. Secure Data Transfer Protocols:</strong>
Suppliers are obligated to use secure communication protocols (e.g., VPNs, encrypted channels) for transferring sensitive information as per AiRo Digital Labs' standards.<br><br>
<strong>c. Data Transfer Logs:</strong>
Maintain logs of data transfers to ensure transparency and traceability. Provide access to these logs for auditing purposes if requested by AiRo Digital Labs.<br><br>
<strong>d. Data Transfer Agreements:</strong>
Suppliers must establish clear agreements and protocols for transferring data to AiRo Digital Labs, including responsibilities, encryption requirements, and other security measures.

			<p class="content-subtitle">
				Secure Disposal of Information
			</p>
			 <strong>a. Data Retention Policy:</strong>
Suppliers shall develop and enforce a data retention policy specifying how long data should be retained and when it should be securely disposed of, aligning with AiRo Digital Labs' policies.<br><br>
<strong>b. Secure Shredding:</strong>
Use secure shredding methods for physical documents and data storage devices in accordance with AiRo Digital Labs' guidelines and certification requirements.<br><br>
<strong>c. Data Wiping:</strong>
Employ secure data wiping techniques for electronic storage devices to prevent data recovery, following AiRo Digital Labs' recommended standards.<br><br>
<strong>d. Documentation of Disposal:</strong>
Maintain records of the disposal process, including dates and methods used, and provide these records to AiRo Digital Labs upon request.

			</p>
			<p class="content-subtitle">
				Personnel and Physical Security
			</p>
			<p>
				 <strong>a. Access Control Systems:</strong>
Suppliers must implement access control systems (e.g., key cards, biometrics) to restrict physical access to facilities as required by AiRo Digital Labs.<br><br>
 <strong>b. Visitor Logs:</strong>
Maintain visitor logs and require visitors to sign in and out when entering and leaving facilities in line with AiRo Digital Labs' visitor access policies.<br><br>
 <strong>c. Employee Background Checks:</strong>
Conduct background checks on employees to ensure trustworthiness and security clearance, if applicable, as specified by AiRo Digital Labs.<br><br>
 <strong>d. Security Awareness Training:</strong>
Provide security awareness training to employees regarding physical security measures and procedures, following AiRo Digital Labs' standards.

			<p class="content-subtitle">
				 Information Access and Handling
			</p>
            <strong>a. Access Requests:</strong>
Suppliers shall establish a formal process for requesting access to information and assets, including approval mechanisms consistent with AiRo Digital Labs' access control policies.<br><br>
<strong>b. Access Logs:</strong>
Maintain access logs to track who accessed what information and when, and provide access to these logs for auditing purposes as needed by AiRo Digital Labs.<br><br>
<strong>c. Data Encryption:</strong>
Suppliers must apply encryption to sensitive data both in storage and during transmission as required by AiRo Digital Labs' encryption standards.<br><br>
<strong>d. Data Handling Procedures:</strong>
Develop and communicate clear procedures for handling sensitive information, including secure storage and disposal, following AiRo Digital Labs' guidelines.<br><br>
<strong>e.   Data Subjects Requests:</strong>
If the Supplier receives requests from data subjects (individuals whose data is processed) regarding their rights under data protection laws, such as access, rectification, erasure, or data portability, the Supplier shall promptly inform AiRo Digital Labs and assist as necessary to fulfill these requests.<br><br>
<strong>f.	Disaster Recovery Site:</strong><br><br>
 <ul>
				
<li>The Supplier is responsible for establishing and maintaining a disaster recovery site at a geographically separate and secure facility. This site will serve as a critical component to ensure the continuity of services in the event of a catastrophic failure or disaster.<br><br>
<li>Regular backups of all critical data and systems will be conducted to minimize data loss, and routine testing and maintenance of the disaster recovery site will be performed to verify its effectiveness in restoring services.<br><br>
<li>The Supplier is also required to maintain up-to-date documentation of the disaster recovery procedures, which shall be made available to AiRo Digital Labs upon request. This clause is essential to guarantee that the Supplier has a robust plan in place for business continuity, safeguarding the interests of AiRo Digital Labs.<br><br></li>
</ul>

<strong>g. Change Management:</strong><br><br>
 <ul>
				
<li>The Supplier shall promptly notify AiRo Digital Labs of any proposed changes to the services or systems that may impact service levels, security, or compliance.<br><br>
<li>The Supplier shall establish a formal change request process that outlines how changes will be documented, evaluated, approved, and implemented. Prior to implementing any changes, the Supplier shall conduct a thorough impact assessment to evaluate potential risks, including security and compliance considerations.<br><br>
<li>Significant changes shall require prior written approval from AiRo Digital Labs, and the Supplier shall provide a detailed plan for implementation. All changes, including their impact assessments, approvals, and implementation plans, shall be documented and made available for review by AiRo Digital Labs.<br><br>
<li>The Supplier shall conduct testing and validation of changes before production implementation to ensure minimal disruption and maintain service levels. A rollback plan shall be in place for each change to mitigate any unforeseen issues, and it shall be communicated to AiRo Digital Labs. This change management process ensures that any changes to the services or systems are carefully planned, evaluated, and documented to minimize risks, disruptions, and maintain compliance and security standards.</li>
</ul>

